BankTranslation = {}
function BankTranslation.Language(player)
    if JrsLang then
        local code = player and JrsLang.Of(player) or JrsLang.Current()
        if code == 'ar' or code == 'en' then return code end
    end
    return Config.Lang == 'Arabic' and 'ar' or 'en'
end
function BankTranslation.For(player)
    local name = BankTranslation.Language(player) == 'ar' and 'Arabic' or 'English'
    return Translation.Langs[name] or Translation.Langs.English
end
